// Helper function to filter venues by location and type
export const getMatchingVenues = (location, type = "all") => {
  return venues.filter((venue) => {
    const matchesLocation = venue.location === location;
    const matchesType =
      type === "all" || venue.type === type || venue.type === "both";
    return matchesLocation && matchesType;
  });
};

// Get all outdoor venues for a location
export const getOutdoorVenues = (location) => {
  return getMatchingVenues(location, "outdoor");
};

// Get all indoor venues for a location
export const getIndoorVenues = (location) => {
  return getMatchingVenues(location, "indoor");
};
